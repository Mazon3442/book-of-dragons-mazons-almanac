    /** One row on a plate: the label, an iron groove with an ember fill and a riveted handle, then the value. Sends when released. */
    private final class JournalSlider extends AbstractWidget {
        private static final int TRACK_Y = 4;
        private final Component label;
        private final DoubleFunction<Component> valueText;
        private final Consumer<Double> onChange;
        private final Consumer<Double> onCommit;
        private final int steps;
        private double value;

        /** {@code steps} above 1 snaps the value to that many evenly spaced positions; 0 is continuous. */
        JournalSlider(int x, int y, int width, double initial, int steps, Component label, DoubleFunction<Component> valueText,
                      Consumer<Double> onChange, Consumer<Double> onCommit) {
            super(x, y, width, ROW_PLATE_H, label);
            this.label = label;
            this.valueText = valueText;
            this.onChange = onChange;
            this.onCommit = onCommit;
            this.steps = steps;
            this.value = Mth.clamp(initial, 0.0, 1.0);
        }

        private int trackX() { return getX() + LABEL_COL; }
        private int trackW() { return width - LABEL_COL - VALUE_COL - 4; }

        private void setFromMouse(double mx) {
            if (!active) return;
            double v = Mth.clamp((mx - (trackX() + 4)) / (trackW() - 12), 0.0, 1.0);
            if (steps > 1) v = Math.round(v * (steps - 1)) / (double) (steps - 1);
            value = v;
            onChange.accept(value);
        }

        @Override
        protected void renderWidget(GuiGraphics g, int mouseX, int mouseY, float partial) {
            int ink = active ? INK : FADED;
            g.blitSprite(sprite("row"), getX(), getY(), width, height);
            Component v = valueText.apply(value);
            int valueWidth = font.width(v);
            String caption = font.plainSubstrByWidth(label.getString(), LABEL_COL - 8);
            g.drawString(font, caption, getX() + 6, getY() + 5, ink, false);
            g.drawString(font, v, getX() + width - 6 - valueWidth, getY() + 5, active ? INK : FADED, false);
            setMessage(label.copy().append(": ").append(v));

            int tx = trackX();
            int tw = trackW();
            int ty = getY() + TRACK_Y;
            g.blitSprite(sprite("slider_track"), tx, ty, tw, 8);
            int fillEnd = tx + 2 + (int) (value * (tw - 12));
            g.fill(tx + 2, ty + 2, fillEnd, ty + 5, active ? EMBER : 0xFF5D5C62);
            g.fill(tx + 2, ty + 2, fillEnd, ty + 3, active ? EMBER_LIGHT : 0xFF7A787F);
            if (steps > 1) {
                for (int i = 0; i < steps; i++) {            // notches so the allowed positions are visible
                    int nx = tx + 4 + (int) Math.round(i * (tw - 12) / (double) (steps - 1));
                    g.fill(nx, ty + 6, nx + 1, ty + 7, 0xFFA2A0A6);
                }
            }
            g.blitSprite(sprite("slider_handle"), fillEnd - 2, ty - 2, 8, 12);
            if (isFocused()) g.renderOutline(tx - 1, ty - 3, tw + 2, 14, EMBER);
        }

        @Override public void onClick(double mx, double my) { if (mx >= trackX() - 2) setFromMouse(mx); }
        @Override protected void onDrag(double mx, double my, double dx, double dy) { setFromMouse(mx); }
        @Override public void onRelease(double mx, double my) { if (active) onCommit.accept(value); }
        @Override
        public boolean keyPressed(int key, int scan, int modifiers) {
            if (!active || !isFocused()) return false;
            if (key == GLFW.GLFW_KEY_LEFT || key == GLFW.GLFW_KEY_RIGHT
                || key == GLFW.GLFW_KEY_HOME || key == GLFW.GLFW_KEY_END) {
                double step = steps > 1 ? 1.0 / (steps - 1) : 0.01;
                double next = key == GLFW.GLFW_KEY_HOME ? 0 : key == GLFW.GLFW_KEY_END ? 1
                    : Mth.clamp(value + (key == GLFW.GLFW_KEY_LEFT ? -step : step), 0, 1);
                if (next != value) {
                    value = next;
                    onChange.accept(value);
                    onCommit.accept(value);
                }
                return true;
            }
            return super.keyPressed(key, scan, modifiers);
        }
        @Override public void playDownSound(SoundManager sounds) { }
        @Override protected void updateWidgetNarration(NarrationElementOutput out) { defaultButtonNarrationText(out); }
    }
