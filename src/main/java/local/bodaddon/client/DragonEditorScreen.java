    @Override
    protected void init() {
        left = (this.width - PANEL_W) / 2;
        top = (this.height - PANEL_H) / 2;

        for (Tab section : Tab.values()) addRenderableWidget(new SectionButton(section));

        if (liveTraits == null) liveTraits = state.traits().clone();
        int x = contentX();
        int y = contentY();
        switch (tab) {
            case BOND -> {
                JournalButton tame = addRenderableWidget(new JournalButton(x, y, COL_W, 20,
                    Component.translatable(state.tame() ? "bodaddon.editor.tamed" : "bodaddon.editor.tame"), true,
                    () -> send(EditAction.TAME, 0, 0)));
                tame.active = !state.tame();
                addRenderableWidget(new JournalSlider(x, y + 25, COL_W, state.bond() / 1000.0, 0,
                    Component.translatable("bodaddon.editor.loyalty"),
                    v -> bondName((int) Math.round(v * 1000)), v -> { },
                    v -> send(EditAction.SET_BOND, 0, (float) (v * 1000))));
            }
            case VITALS -> {
                float[] steps = state.healthSteps();
                int n = steps.length;
                JournalSlider maxHealth = addRenderableWidget(new JournalSlider(x, y, COL_W,
                    n > 1 ? state.healthStep() / (double) (n - 1) : 0.0, n,
                    Component.translatable("bodaddon.editor.max_health"),
                    v -> Component.literal(n == 0 ? String.valueOf(Math.round(state.maxHealth()))
                        : String.valueOf(Math.round(steps[(int) Math.round(v * (n - 1))]))),
                    v -> { },
                    v -> send(EditAction.SET_MAX_HEALTH, (int) Math.round(v * (n - 1)), 0)));
                maxHealth.active = n > 1;
                float max = Math.max(1.0F, state.maxHealth());
                addRenderableWidget(new JournalSlider(x, y + ROW_STEP, COL_W, (state.health() - 1.0F) / Math.max(1.0F, max - 1.0F), 0,
                    Component.translatable("bodaddon.editor.health_label"),
                    v -> Component.literal(Math.round(1.0F + v * (max - 1.0F)) + " / " + Math.round(max)), v -> { },
                    v -> send(EditAction.SET_HEALTH, 0, (float) (1.0F + v * (max - 1.0F)))));
                // the two status rows (injury, breeding timer) are drawn between the sliders and the buttons
                JournalButton heal = addRenderableWidget(new JournalButton(x, y + 4 * ROW_STEP, COL_W, 20,
                    Component.translatable("bodaddon.editor.clear_injury"), true, () -> send(EditAction.CLEAR_INJURY, 0, 0)));
                heal.active = state.injured();
                JournalButton timer = addRenderableWidget(new JournalButton(x, y + 4 * ROW_STEP + 24, COL_W, 20,
                    Component.translatable("bodaddon.editor.clear_breeding"), true, () -> send(EditAction.CLEAR_BREEDING, 0, 0)));
                timer.active = state.breedingTicks() > 0;
            }
            case PERSONALITY -> {
                for (int i = 0; i < Traits.COUNT; i++) {
                    final int index = i;
                    addRenderableWidget(new JournalSlider(x, y + i * ROW_STEP, COL_W, state.traits()[i], 0,
                        Component.translatable(Traits.langKey(index)),
                        v -> Component.literal(Math.round(v * 100) + "%"),
                        v -> liveTraits[index] = v.floatValue(),
                        v -> send(EditAction.SET_TRAIT, index, v.floatValue())));
                }
            }
            case VARIANTS -> {
                VariantRow[] rows = variants.shown;
                if (variants.pickerRow >= 0) {
                    final int row = variants.pickerRow;
                    addRenderableWidget(variants.new OptionList(font, VariantsPanel.Skin.SLATE, x, y, COL_W, rows[row], option -> send(EditAction.SET_VARIANT, variants.shownIndex[row], option)));
                } else {
                    variantPage = Mth.clamp(variantPage, 0, variants.pages() - 1);
                    for (int i = 0; i < ROWS_PER_PAGE; i++) {
                        final int row = variantPage * ROWS_PER_PAGE + i;
                        if (row >= rows.length) break;
                        addRenderableWidget(new VariantButton(x, y + i * ROW_STEP, COL_W, rows[row], () -> openPicker(row)));
                    }
                    if (variants.pages() > 1) {
                        JournalButton prev = addRenderableWidget(new JournalButton(x, y + ROWS_PER_PAGE * ROW_STEP + 2, 28, 16,
                            Component.literal("<"), false, () -> turnPage(-1)));
                        JournalButton next = addRenderableWidget(new JournalButton(x + COL_W - 28, y + ROWS_PER_PAGE * ROW_STEP + 2, 28, 16,
                            Component.literal(">"), false, () -> turnPage(1)));
                        prev.active = variantPage > 0;
                        next.active = variantPage < variants.pages() - 1;
                    }
                }
            }
            case SOCIAL -> addRenderableWidget(new JournalButton(x, y, COL_W, 20,
                Component.translatable("bodaddon.editor.befriend"), true, () -> send(EditAction.BEFRIEND_NEARBY, 0, 0)));
        }

        addRenderableWidget(new JournalButton(left + PANEL_W - 12 - 56, top + FOOTER_Y, 56, 14,
            Component.translatable(picking() ? "gui.back" : "gui.done"), false, picking() ? this::closePicker : this::onClose));
    }

