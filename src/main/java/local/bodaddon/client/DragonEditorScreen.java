    private static final int TAB_W = 48;
    private static final int TAB_STEP = 52;
    private static final int TAB_X = 48;
    private static final int TAB_H = 36;
    private static final int TAB_SELECTED_H = 44;
    private static final int TAB_RISE = 26;       // how far a tab hangs above the frame

    private int tabX(Tab t) { return left + TAB_X + t.ordinal() * TAB_STEP; }
    private int tabY() { return top - TAB_RISE; }
    private int tabH(Tab t) { return t == tab ? TAB_SELECTED_H : TAB_H; }

    private Tab ribbonAt(double mx, double my) {
        for (Tab t : Tab.values()) {
            if (mx >= tabX(t) && mx < tabX(t) + TAB_W && my >= tabY() && my < tabY() + tabH(t)) return t;
        }
        return null;
    }

    private void drawTabs(GuiGraphics g) {
        for (Tab t : Tab.values()) {
            boolean selected = t == tab;
            int x = tabX(t);
            g.blitSprite(sprite(selected ? "tab_cloth_selected" : "tab_cloth"), x, tabY(), TAB_W, tabH(t));
            g.blitSprite(sprite("icon_" + t.icon), x + (TAB_W - 13) / 2, tabY() + 9, 13, 13);
            Component label = t.label();
            g.drawString(font, label, x + (TAB_W - font.width(label)) / 2, tabY() + 24, selected ? INK : FADED, true);
        }
    }

    private void selectTab(Tab next) {
        if (next == tab) return;
        tab = next;
        remembered = next;
        variants.closePicker();
        draggingView = false;
        rebuildWidgets();
        for (var child : children()) {
            if (child instanceof SectionButton button && button.section == next) {
                setFocused(button);
                break;
            }
        }
    }

    @Override
    public boolean mouseClicked(double mx, double my, int button) {
        if (button == 0 && overViewport(mx, my)) {
            draggingView = true;
            return true;
        }
        return super.mouseClicked(mx, my, button);
    }

