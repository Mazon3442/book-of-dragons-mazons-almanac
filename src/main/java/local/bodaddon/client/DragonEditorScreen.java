    // --- personality radar --------------------------------------------------------------------

    private static double axisX(int i) { return Math.cos(Math.toRadians(-90 + 60 * i)); }
    private static double axisY(int i) { return Math.sin(Math.toRadians(-90 + 60 * i)); }

    private void drawRadar(GuiGraphics g, int cx, int cy, int r) {
        for (int ring = 1; ring <= 3; ring++) {
            int rr = r * ring / 3;
            int[] xs = new int[Traits.COUNT];
            int[] ys = new int[Traits.COUNT];
            for (int i = 0; i < Traits.COUNT; i++) {
                xs[i] = cx + (int) Math.round(axisX(i) * rr);
                ys[i] = cy + (int) Math.round(axisY(i) * rr);
            }
            polyline(g, xs, ys, ring == 3 ? 0xFF7A787F : IRON_MID);
        }
        for (int i = 0; i < Traits.COUNT; i++) {
            line(g, cx, cy, cx + (int) Math.round(axisX(i) * r), cy + (int) Math.round(axisY(i) * r), IRON_LIGHT);
        }
        int[] px = new int[Traits.COUNT];
        int[] py = new int[Traits.COUNT];
        for (int i = 0; i < Traits.COUNT; i++) {
            double reach = r * (0.06 + 0.94 * Mth.clamp(liveTraits[i], 0.0F, 1.0F));
            px[i] = cx + (int) Math.round(axisX(i) * reach);
            py[i] = cy + (int) Math.round(axisY(i) * reach);
        }
        fillPolygon(g, px, py, 0x66FA801A);
        polyline(g, px, py, EMBER);
        for (int i = 0; i < Traits.COUNT; i++) g.fill(px[i] - 1, py[i] - 1, px[i] + 1, py[i] + 1, EMBER_LIGHT);
        for (int i = 0; i < Traits.COUNT; i++) {
            String label = Component.translatable(Traits.chartKey(i) + ".code").getString();
            int vx = cx + (int) Math.round(axisX(i) * r);
            int vy = cy + (int) Math.round(axisY(i) * r);
            int w = font.width(label);
            int x = i == 0 || i == 3 ? vx - w / 2 : (i == 1 || i == 2 ? vx + 3 : vx - w - 2);
            x = Mth.clamp(x, leftX(), leftX() + LEFT_W - w);
            int y = i == 0 ? vy - 10 : i == 3 ? vy + 3 : (i == 1 || i == 5 ? vy - 8 : vy + 1);
            g.drawString(font, label, x, y, INK, false);
        }
    }

    private static void line(GuiGraphics g, int x0, int y0, int x1, int y1, int color) {
        int dx = Math.abs(x1 - x0);
        int dy = -Math.abs(y1 - y0);
        int sx = x0 < x1 ? 1 : -1;
        int sy = y0 < y1 ? 1 : -1;
        int err = dx + dy;
        while (true) {
            g.fill(x0, y0, x0 + 1, y0 + 1, color);
            if (x0 == x1 && y0 == y1) break;
            int e2 = 2 * err;
            if (e2 >= dy) { err += dy; x0 += sx; }
            if (e2 <= dx) { err += dx; y0 += sy; }
        }
    }

    private static void polyline(GuiGraphics g, int[] xs, int[] ys, int color) {
        for (int i = 0; i < xs.length; i++) {
            int j = (i + 1) % xs.length;
            line(g, xs[i], ys[i], xs[j], ys[j], color);
        }
    }

    /** Scanline fill of a small convex polygon, one pixel row at a time so the edge stays crisp. */
    private static void fillPolygon(GuiGraphics g, int[] xs, int[] ys, int color) {
        int minY = Integer.MAX_VALUE;
        int maxY = Integer.MIN_VALUE;
        for (int y : ys) {
            minY = Math.min(minY, y);
            maxY = Math.max(maxY, y);
        }
        for (int y = minY; y <= maxY; y++) {
            double lo = Double.MAX_VALUE;
            double hi = -Double.MAX_VALUE;
            double sy = y + 0.5;
            for (int i = 0; i < xs.length; i++) {
                int j = (i + 1) % xs.length;
                double y0 = ys[i];
                double y1 = ys[j];
                if ((y0 <= sy && y1 > sy) || (y1 <= sy && y0 > sy)) {
                    double x = xs[i] + (sy - y0) * (xs[j] - xs[i]) / (y1 - y0);
                    lo = Math.min(lo, x);
                    hi = Math.max(hi, x);
                }
            }
            if (hi >= lo) g.fill((int) Math.round(lo), y, (int) Math.round(hi) + 1, y + 1, color);
        }
    }

    @Override
    public void render(GuiGraphics g, int mouseX, int mouseY, float partial) {
        super.render(g, mouseX, mouseY, partial);   // background and decor first, then the widgets
        drawTabText(g, contentX(), contentY());

        Tab hovered = ribbonAt(mouseX, mouseY);
        if (hovered != null) g.renderTooltip(font, hovered.title(), mouseX, mouseY);
        if (mouseX >= left + PANEL_W - 115 && mouseX < left + PANEL_W - 17
            && mouseY >= top + 10 && mouseY < top + 23) {
            g.renderTooltip(font, Component.literal(state.name()), mouseX, mouseY);
        }
    }


    private void drawTabText(GuiGraphics g, int x, int y) {
        switch (tab) {
            case BOND -> wrap(g, Component.translatable("bodaddon.editor.bond." + bondTier(state.bond()) + ".desc"), x, y + 52);
            case VITALS -> {
                statusRow(g, y + 2 * ROW_STEP, Component.translatable("bodaddon.editor.injury_label"),
                    state.injured() ? "dot_warn" : "dot_ok",
                    Component.translatable(state.injured() ? "bodaddon.editor.injured" : "bodaddon.editor.healthy"));
                int secs = state.breedingTicks() / 20;
                statusRow(g, y + 3 * ROW_STEP, Component.translatable("bodaddon.editor.breeding_label"),
                    state.breedingTicks() > 0 ? "dot_ember" : "dot_ok",
                    state.breedingTicks() > 0
                        ? Component.translatable("bodaddon.editor.breeding_value", secs / 60, String.format("%02d", secs % 60))
                        : Component.translatable("bodaddon.editor.breeding_none"));
            }
            case VARIANTS -> {
                if (variants.shown.length == 0) {
                    wrap(g, Component.translatable("bodaddon.editor.variants.none"), x, y);
                } else if (variants.pickerRow < 0 && variants.pages() > 1) {
                    Component page = Component.translatable("bodaddon.editor.variants.page", variantPage + 1, variants.pages());
                    g.drawString(font, page, x + (COL_W - font.width(page)) / 2, y + ROWS_PER_PAGE * ROW_STEP + 6, FADED, false);
                }
            }
            case SOCIAL -> wrap(g, Component.translatable("bodaddon.editor.befriend.desc"), x, y + 28);
            default -> { }
        }
    }

    /** A label on a plate with a read-only dark field: a status dot and its text. */
    private void statusRow(GuiGraphics g, int y, Component label, String dot, Component text) {
        int x = contentX();
        g.blitSprite(sprite("row"), x, y, COL_W, ROW_PLATE_H);
        g.drawString(font, font.plainSubstrByWidth(label.getString(), LABEL_COL - 8), x + 6, y + 5, INK, false);
        int fx = x + LABEL_COL;
        g.blitSprite(sprite("readout"), fx, y + 3, COL_W - LABEL_COL - 4, 11);
        g.blitSprite(sprite(dot), fx + 4, y + 6, 5, 5);
        g.drawString(font, text, fx + 13, y + 4, INK, false);
    }

    private void wrap(GuiGraphics g, Component text, int x, int y) {
        List<FormattedCharSequence> lines = font.split(text, COL_W);
        for (int i = 0; i < lines.size(); i++) g.drawString(font, lines.get(i), x, y + i * 10, FADED, false);
    }

